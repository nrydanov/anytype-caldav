    /// Several chosen lead times become several `VALARM`s on one `VTODO`,
    /// which RFC 5545 permits and which keeps the feed saying the same thing
    /// the push scheduler will do.
    #[test]
    fn per_task_lead_times_produce_one_alarm_each() {
        let mut t = task("a", "One");
        t.deadline = date("2026-09-03T18:00:00+04:00");
        t.reminder_leads = vec![chrono::Duration::hours(2), chrono::Duration::days(1)];

        let ics = renderer().render(&[t]).unwrap();

        assert!(
            ics.contains("TRIGGER;VALUE=DATE-TIME:20260902T140000Z"),
            "{ics}"
        );
        assert!(
            ics.contains("TRIGGER;VALUE=DATE-TIME:20260903T120000Z"),
            "{ics}"
        );
        let reader = ical::IcalParser::new(std::io::BufReader::new(ics.as_bytes()));
        let calendars: Vec<_> = reader.collect::<Result<Vec<_>, _>>().expect("parses");
        assert_eq!(calendars[0].todos[0].alarms.len(), 2);
    }

    #[test]
    fn an_empty_task_list_still_produces_a_valid_calendar() {
        let ics = renderer().render(&[]).unwrap();
        assert!(ics.contains("BEGIN:VCALENDAR"), "{ics}");
        assert!(!ics.contains("BEGIN:VTODO"), "{ics}");
        let reader = ical::IcalParser::new(std::io::BufReader::new(ics.as_bytes()));
        let calendars: Vec<_> = reader.collect::<Result<Vec<_>, _>>().expect("parses");
        assert_eq!(calendars.len(), 1);
        assert!(calendars[0].todos.is_empty());
    }
