    #[test]
    fn a_time_of_day_becomes_a_utc_instant() {
        let mut t = task("a", "One");
        t.scheduled = date("2026-08-29T14:30:00+04:00");
        let ics = renderer().render(&[t]).unwrap();
        assert!(ics.contains("DTSTART:20260829T103000Z"), "{ics}");
    }

    #[test]
    fn a_task_without_dates_stays_undated() {
        let ics = renderer().render(&[task("a", "One")]).unwrap();
        assert!(!ics.contains("DTSTART"), "{ics}");
        assert!(!ics.contains("DUE"), "{ics}");
    }

    #[test]
    fn components_are_ordered_by_uid_regardless_of_input_order() {
        let forward = renderer()
            .render(&[task("a", "A"), task("b", "B"), task("c", "C")])
            .unwrap();
        let reversed = renderer()
            .render(&[task("c", "C"), task("b", "B"), task("a", "A")])
            .unwrap();
        assert_eq!(forward, reversed, "output must not depend on input order");
    }

    #[test]
    fn a_duplicate_uid_fails_the_render() {
        let err = renderer()
            .render(&[task("same", "First"), task("same", "Second")])
            .unwrap_err();
        assert!(matches!(err, RenderError::DuplicateUid { .. }), "{err:?}");
    }

    #[test]
    fn dtstamp_uses_last_modified_and_is_stable_between_renders() {
        let mut t = task("a", "One");
        t.last_modified = Some(Utc.with_ymd_and_hms(2026, 8, 29, 12, 0, 0).unwrap());
        let renderer = renderer();
        let first = renderer.render(std::slice::from_ref(&t)).unwrap();
        let second = renderer.render(std::slice::from_ref(&t)).unwrap();
        assert!(first.contains("DTSTAMP:20260829T120000Z"), "{first}");
        assert_eq!(first, second, "repeated renders must be byte-identical");
    }

    #[test]
    fn dtstamp_falls_back_to_the_process_timestamp() {
        let ics = renderer().render(&[task("a", "One")]).unwrap();
        assert!(ics.contains("DTSTAMP:20260101T000000Z"), "{ics}");
    }

    #[test]
    fn escapes_special_characters_and_preserves_unicode() {
        let ics = renderer()
            .render(&[task("a", "Купить: хлеб, молоко; сыр \\ и всё")])
            .unwrap();
        let unfolded = ics.replace("\r\n ", "");
        assert!(unfolded.contains("хлеб"), "unicode preserved: {unfolded}");
        assert!(unfolded.contains("\\,"), "comma escaped: {unfolded}");
        assert!(unfolded.contains(r"\;"), "semicolon escaped: {unfolded}");
    }

    #[test]
    fn folds_physical_lines_to_the_rfc_limit() {
        let long = "Очень длинное название задачи ".repeat(12);
        let ics = renderer().render(&[task("a", &long)]).unwrap();
        for line in ics.split("\r\n") {
            assert!(
                line.len() <= 75,
                "line of {} octets exceeds the RFC 5545 limit: {line}",
                line.len()
            );
        }
    }

    /// Parsed by a different crate than the one that produced it: a serializer
    /// validating its own output proves very little.
    #[test]
    fn output_is_accepted_by_an_independent_parser() {
        let mut done = task("b", "Done one");
        done.done = true;
        done.deadline = date("2026-08-30T00:00:00+04:00");
        let mut timed = task("a", "Timed one");
        timed.scheduled = date("2026-08-29T14:30:00+04:00");

        let ics = renderer().render(&[timed, done]).unwrap();

        let reader = ical::IcalParser::new(std::io::BufReader::new(ics.as_bytes()));
        let calendars: Vec<_> = reader.collect::<Result<Vec<_>, _>>().expect("parses");
        assert_eq!(calendars.len(), 1);
        let todos = &calendars[0].todos;
        assert_eq!(todos.len(), 2, "both tasks survive a round trip");

        let uids: Vec<_> = todos
            .iter()
            .filter_map(|todo| {
                todo.properties
                    .iter()
                    .find(|p| p.name == "UID")
                    .and_then(|p| p.value.clone())
            })
            .collect();
        assert_eq!(
            uids,
            vec![
                "a@anytype-task-exporter".to_string(),
                "b@anytype-task-exporter".to_string()
            ]
        );
    }

